/**
 * A seeded generator of numbers in [0, 1): the same seed always gives the
 * same numbers, on every machine (mulberry32). For music and anything else
 * that must not change between renders; never `Math.random()`.
 */
export const seededRandom = (seed: number): (() => number) => {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
};
